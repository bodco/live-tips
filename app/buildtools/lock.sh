#!/bin/bash
# Pacenote 0.24.1 (F1): regenerates Resources/python/*.lock (exact versions with SHA-256 hashes, Python 3.13, macOS
# arm64, wheels only). Run when updating the libraries; the next app release then updates them on every Mac (setup.sh
# check sees other versions than the lock and Install brings them in line). Needs uv. Python itself: setup.sh PY_*.
set -eu
cd "$(dirname "$0")/../Resources/python"
C=(--python-version 3.13 --python-platform aarch64-apple-darwin --only-binary :all: --generate-hashes --no-header)
uv pip compile all.in "${C[@]}" -o /tmp/pacenote-all.lock
for g in recorder tips voices; do
  uv pip compile "$g.in" "${C[@]}" --no-annotate -c /tmp/pacenote-all.lock -o "/tmp/pacenote-$g.lock"
  { echo "# Pacenote 0.24.1 (F1): locked $g packages for Python 3.13, macOS arm64. Generated by app/buildtools/lock.sh, do not edit by hand."
    cat "/tmp/pacenote-$g.lock"; } > "$g.lock"
done
echo "locks updated: $(grep -chE '^[a-z]' recorder.lock tips.lock voices.lock | paste -sd+ - | bc) pins"
