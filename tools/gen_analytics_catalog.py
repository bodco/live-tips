#!/usr/bin/env python3
"""App 0.19.0 (S4, D43): embeds rules/analytics.yaml in the app as JSON (LiveTipsCore/AnalyticsCatalog.swift).

The app has no YAML parser; the catalog goes in as a JSON string with the SHA-256 of the YAML it came from. CoreChecks
hashes rules/analytics.yaml again and fails when the embedded copy is older. Run after every catalog change:
    python3 tools/gen_analytics_catalog.py
"""
import hashlib
import json
import pathlib

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "rules" / "analytics.yaml"
OUT = ROOT / "app" / "Sources" / "LiveTipsCore" / "AnalyticsCatalog.swift"

raw = SRC.read_bytes()
cat = yaml.safe_load(raw)
cat["screens"] = {k: [str(x) for x in (v or [])] for k, v in cat["screens"].items()}
cat["events"] = {k: (v or {}) for k, v in cat["events"].items()}
cat["values"] = cat.get("values") or {}
body = json.dumps({k: cat[k] for k in ("schema_version", "types", "enums", "screens", "actions", "events", "values")},
                  sort_keys=True, separators=(",", ":"), ensure_ascii=True)
assert '"""#' not in body
OUT.write_text(f'''// Generated by tools/gen_analytics_catalog.py from rules/analytics.yaml. Do not edit: change the YAML and run the tool.
// CoreChecks fails when this copy is older than the YAML (sourceSHA256).

enum AnalyticsCatalogData {{
    static let sourceSHA256 = "{hashlib.sha256(raw).hexdigest()}"
    static let json = #"""
{body}
"""#
}}
''')
print(f"{OUT.name}: {len(cat['events'])} events, {len(cat['screens'])} screens, {len(cat['actions'])} actions")
